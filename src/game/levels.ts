import { BORDER, WORLD_W, type Level, type Rect } from "./types";

function room(opts: {
  id: string;
  name: string;
  subtitle: string;
  hint: string;
  par: number;
  bottom?: Rect[] | "full" | "none";
  startPad: Rect;
  goalPad: Rect;
  pads?: Rect[];
  voids: Rect[];
}): Level {
  return {
    id: opts.id,
    name: opts.name,
    subtitle: opts.subtitle,
    hint: opts.hint,
    par: opts.par,
    solids: [
      ...walls(opts.bottom ?? "full"),
      opts.startPad,
      opts.goalPad,
      ...(opts.pads ?? []),
    ],
    voids: opts.voids,
    start: restAbove(opts.startPad),
    ...goalFromPad(opts.goalPad, 18),
  };
}

